"""Generate the SQL scripts in `database/` from the Python source of truth.

* `database/schema.sql`      - the MySQL 8 DDL of every table (compiled from the
                                SQLAlchemy metadata with the MySQL dialect)
* `database/seed.sql`        - the demo data (from `app/db/seed_data.py`)
* `database/views.sql`       - the five views (from `app/db/views.py`)
* `database/experiments/*.sql` - the nine DBMS experiments (from
                                `app/queries/sql_lab.py`)

Run with:  python backend/scripts/generate_sql.py
"""
from __future__ import annotations

import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
ROOT_DIR = BACKEND_DIR.parent
sys.path.insert(0, str(BACKEND_DIR))

from sqlalchemy.dialects import mysql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.db import seed_data as sd  # noqa: E402
from app.db.views import VIEW_DEFINITIONS  # noqa: E402
from app.models import metadata  # noqa: E402
from app.queries.sql_lab import EXPERIMENTS  # noqa: E402

DATABASE_DIR = ROOT_DIR / "database"
EXPERIMENTS_DIR = DATABASE_DIR / "experiments"

HEADER = """-- ------------------------------------------------------------------
-- EventEase - {title}
-- {subtitle}
--
-- Generated by `backend/scripts/generate_sql.py` - do not edit by hand,
-- change the Python source (app/models, app/db/seed_data.py, app/db/views.py)
-- and run the generator again.
-- ------------------------------------------------------------------
"""


def mysql_datetime(day_offset: int, time_of_day: str = "10:00:00") -> str:
    """MySQL expression for a date/time relative to today."""
    return f"TIMESTAMP(DATE_ADD(CURDATE(), INTERVAL {day_offset} DAY), '{time_of_day}')"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"written: {path.relative_to(ROOT_DIR)}")


def _sql_string(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _event_id(event: sd.EventSeed) -> int:
    """Position of the event inside the seed list (1 based)."""
    return sd.EVENTS.index(event) + 1


# ---------------------------------------------------------------------------
# schema.sql
# ---------------------------------------------------------------------------
def generate_schema() -> None:
    lines = [
        HEADER.format(title="Database schema (MySQL 8.0)", subtitle="All tables, constraints and indexes"),
        "",
        "CREATE DATABASE IF NOT EXISTS eventease",
        "    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
        "USE eventease;",
        "",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "",
    ]
    dialect = mysql.dialect()
    for table in metadata.sorted_tables:
        lines.append("-- " + "-" * 66)
        lines.append(f"-- Table: {table.name}")
        lines.append("-- " + "-" * 66)
        lines.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for index in sorted(table.indexes, key=lambda item: item.name or ""):
            lines.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        lines.append("")

    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    lines.append("")
    write(DATABASE_DIR / "schema.sql", "\n".join(lines))


# ---------------------------------------------------------------------------
# views.sql
# ---------------------------------------------------------------------------
def generate_views() -> None:
    lines = [
        HEADER.format(title="SQL views", subtitle="Five reusable views used by the dashboard and the reports"),
        "",
        "USE eventease;",
        "",
    ]
    for name, body in VIEW_DEFINITIONS:
        lines.append("-- " + "-" * 66)
        lines.append(f"-- View: {name}")
        lines.append("-- " + "-" * 66)
        lines.append(f"CREATE OR REPLACE VIEW {name} AS")
        lines.append(body.strip() + ";")
        lines.append("")
    write(DATABASE_DIR / "views.sql", "\n".join(lines))


# ---------------------------------------------------------------------------
# seed.sql
# ---------------------------------------------------------------------------
def generate_seed() -> None:
    lines = [
        HEADER.format(title="Sample data", subtitle="Realistic demo data for the EventEase dashboard"),
        "",
        "USE eventease;",
        "",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "",
        "-- ------------------------------------------------------------------",
        "-- Organizers",
        "-- ------------------------------------------------------------------",
        "INSERT INTO organizers (organizer_id, organizer_name, email, phone, organization_name, created_at) VALUES",
    ]
    lines.append(
        ",\n".join(
            "    ({id}, {name}, {email}, {phone}, {org}, CURRENT_TIMESTAMP)".format(
                id=index,
                name=_sql_string(organizer["organizer_name"]),
                email=_sql_string(organizer["email"]),
                phone=_sql_string(organizer.get("phone")),
                org=_sql_string(organizer.get("organization_name")),
            )
            for index, organizer in enumerate(sd.ORGANIZERS, start=1)
        )
        + ";"
    )
    lines.append("")

    lines.append("-- ------------------------------------------------------------------")
    lines.append("-- Venues")
    lines.append("-- ------------------------------------------------------------------")
    lines.append(
        "INSERT INTO venues (venue_id, venue_name, location, capacity, venue_type, availability_status) VALUES"
    )
    lines.append(
        ",\n".join(
            "    ({id}, {name}, {location}, {capacity}, {type}, {status})".format(
                id=index,
                name=_sql_string(venue["venue_name"]),
                location=_sql_string(venue["location"]),
                capacity=venue["capacity"],
                type=_sql_string(venue.get("venue_type")),
                status=_sql_string(venue["availability_status"]),
            )
            for index, venue in enumerate(sd.VENUES, start=1)
        )
        + ";"
    )
    lines.append("")

    lines.append("-- ------------------------------------------------------------------")
    lines.append("-- Attendees")
    lines.append("-- ------------------------------------------------------------------")
    lines.append(
        "INSERT INTO attendees (attendee_id, full_name, email, phone, organization, registration_date) VALUES"
    )
    lines.append(
        ",\n".join(
            "    ({id}, {name}, {email}, {phone}, {org}, DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 60 DAY))".format(
                id=index,
                name=_sql_string(attendee["full_name"]),
                email=_sql_string(attendee["email"]),
                phone=_sql_string(attendee.get("phone")),
                org=_sql_string(attendee.get("organization")),
            )
            for index, attendee in enumerate(sd.ATTENDEES, start=1)
        )
        + ";"
    )
    lines.append("")

    lines.append("-- ------------------------------------------------------------------")
    lines.append("-- Events  (the dates are relative to CURDATE() so that the dashboard")
    lines.append("--            always contains completed, ongoing and upcoming events)")
    lines.append("-- ------------------------------------------------------------------")
    for event_index, event in enumerate(sd.EVENTS, start=1):
        lines.append(("-- {key} {name}".format(key=event.key, name=event.event_name)).ljust(112, "-"))
        lines.append(
            """INSERT INTO events (event_id, event_name, description, event_category, organizer_id, venue_id, event_date,
       start_time, end_time, capacity, ticket_price, event_status, created_at)
VALUES ({id}, {name}, {description}, {category}, {organizer}, {venue},
        {date}, {start}, {end}, {capacity}, {price}, {status}, DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 90 DAY));""".format(
                id=event_index,
                name=_sql_string(event.event_name),
                description=_sql_string(event.description),
                category=_sql_string(event.event_category),
                organizer=event.organizer,
                venue=event.venue,
                date=mysql_datetime(event.day_offset),
                start=event.start_time,
                end=event.end_time,
                capacity=event.capacity,
                price=f"{event.ticket_price:.2f}",
                status=_sql_string(event.event_status),
            )
        )
    lines.append("")

    lines.append("-- ------------------------------------------------------------------")
    lines.append("-- Registrations and payments")
    lines.append("-- ------------------------------------------------------------------")
    registration_values: list[str] = []
    payment_values: list[str] = []
    registration_id = 0
    payment_id = 0
    for event in sd.EVENTS:
        for seed in event.registrations:
            registration_id += 1
            ticket_price = event.ticket_price if seed.amount is None else seed.amount
            registration_values.append(
                """    ({registration_id}, {attendee}, {event}, {date}, '{status}', '{attendance}', {ticket_type}, {price})""".format(
                    registration_id=registration_id,
                    attendee=seed.attendee,
                    event=_event_id(event),
                    date=mysql_datetime(event.day_offset - seed.days_before_event),
                    status=seed.status,
                    attendance=seed.attendance,
                    ticket_type=_sql_string(seed.ticket_type),
                    price=f"{ticket_price:.2f}",
                )
            )
            if seed.payment_status is not None:
                payment_id += 1
                payment_values.append(
                    """    ({payment_id}, {registration_id}, {amount}, '{method}', '{status}', {reference}, {date})""".format(
                        payment_id=payment_id,
                        registration_id=registration_id,
                        amount=f"{ticket_price:.2f}",
                        method=seed.payment_method,
                        status=seed.payment_status,
                        reference=_sql_string(f"TXN-{event.key}-{seed.attendee:02d}"),
                        date=mysql_datetime(event.day_offset - seed.days_before_event + 1),
                    )
                )

    lines.append("INSERT INTO registrations (registration_id, attendee_id, event_id, registration_date,")
    lines.append("       registration_status, attendance_status, ticket_type, ticket_price) VALUES")
    lines.append(",\n".join(registration_values) + ";")
    lines.append("")
    lines.append("INSERT INTO payments (payment_id, registration_id, amount, payment_method, payment_status,")
    lines.append("       transaction_reference, payment_date) VALUES")
    lines.append(",\n".join(payment_values) + ";")
    lines.append("")
    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    lines.append("")
    write(DATABASE_DIR / "seed.sql", "\n".join(lines))


# ---------------------------------------------------------------------------
# experiments/*.sql
# ---------------------------------------------------------------------------
def generate_experiments() -> None:
    for experiment in EXPERIMENTS:
        file_name = f"{experiment.number:02d}_{experiment.key.replace('-', '_')}.sql"
        lines = [
            "-- ==================================================================",
            f"-- Experiment {experiment.number}: {experiment.title}",
            f"-- DBMS concept: {experiment.concept}",
            "-- ==================================================================",
            "--",
            f"-- {experiment.description}",
            "--",
        ]
        for note in experiment.notes:
            lines.append(f"-- * {note}")
        lines.append("--")
        lines.append("-- These statements are executed by the SQL Lab of the EventEase")
        lines.append("-- application (POST /api/sql-lab/experiments/{key}/run).")
        lines.append("")
        for index, statement in enumerate(experiment.statements, start=1):
            lines.append("-- " + "-" * 68)
            lines.append(f"-- {index}. {statement.label}")
            if statement.note:
                lines.append(f"--    {statement.note}")
            if statement.native_sql:
                lines.append(
                    "--    MySQL >= 8.0.31 executes the native set operator; on older servers the"
                )
                lines.append(
                    "--    application runs the equivalent EXISTS / NOT EXISTS query instead."
                )
            lines.append("-- " + "-" * 68)
            sql = (statement.native_sql or statement.sql).strip()
            if not sql.upper().startswith(("SELECT", "WITH")):
                sql = sql.rstrip(";")
            lines.append(sql + ";")
            lines.append("")
        write(EXPERIMENTS_DIR / file_name, "\n".join(lines))


def main() -> None:
    generate_schema()
    generate_views()
    generate_seed()
    generate_experiments()


if __name__ == "__main__":
    main()
